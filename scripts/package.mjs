import { readdir, readFile, writeFile, mkdir, chmod, rm } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const all = ['bun-darwin-arm64', 'bun-linux-x64'];
let targets = args.includes('--all') ? all : [`bun-${process.platform}-${process.arch}`];
const targetIndex = args.indexOf('--target');
if (targetIndex !== -1) {
  const target = args[targetIndex + 1];
  if (!all.includes(target)) throw new Error(`Invalid target. Choose ${all.join(', ')}`);
  targets = [target];
}
if (targets.some(target => !all.includes(target)))
  throw new Error(`Unsupported native platform. Use --all or --target ${all.join(' / ')}.`);
// Bun can leave temporary executable files in its working directory.
// Only remove regular files with Bun's generated filename format.
async function cleanBunBuildFiles() {
  for (const entry of await readdir(root, { withFileTypes: true })) {
    if (entry.isFile() && /^\.[a-f0-9]+-[a-f0-9]+\.bun-build$/i.test(entry.name)) {
      await rm(join(root, entry.name), { force: true });
    }
  }
}
await cleanBunBuildFiles();
try {
  execFileSync(process.execPath, ['run', 'build'], { cwd: root, stdio: 'inherit' });
  const assets = {};
  const mime = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'text/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.svg': 'image/svg+xml',
  };
  async function collect(directory, prefix = '') {
    for (const file of await readdir(directory, { withFileTypes: true })) {
      const name = join(directory, file.name),
        url = `${prefix}/${file.name}`;
      if (file.isDirectory()) await collect(name, url);
      else
        assets[url] = {
          body: (await readFile(name)).toString('base64'),
          type: mime[file.name.slice(file.name.lastIndexOf('.'))] ?? 'application/octet-stream',
        };
    }
  }
  await collect(join(root, 'dist'));
  await writeFile(
    join(root, 'server/generated-assets.ts'),
    `// Generated by scripts/package.mjs\nexport const assets = ${JSON.stringify(assets)};\n`,
  );
  for (const target of targets) {
    const directory = join(root, 'release', target.replace('bun-', ''));
    await mkdir(directory, { recursive: true });
    const executable = 'harness-emulator';
    execFileSync(
      process.execPath,
      [
        'build',
        '--compile',
        `--target=${target}`,
        '--minify',
        'server/index.ts',
        '--outfile',
        join(directory, executable),
      ],
      { cwd: root, stdio: 'inherit' },
    );
    await chmod(join(directory, executable), 0o755);
    const archive = join(root, 'release', `harness-emulator-${target.replace('bun-', '')}.tar.gz`);
    execFileSync('tar', ['-czf', archive, '-C', join(root, 'release'), target.replace('bun-', '')], {
      stdio: 'inherit',
    });
    console.log(`\nReady: ${directory}\nArchive: ${archive}\n`);
  }
} finally {
  await cleanBunBuildFiles();
}
